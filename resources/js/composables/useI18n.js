import { computed, ref } from 'vue';

const storageKey = 'wish-gift-locale';
const fallbackLocale = 'lv';

export const languages = [
    { code: 'lv', label: 'LV', title: 'Latviešu' },
    { code: 'en', label: 'EN', title: 'English' },
    { code: 'ru', label: 'RU', title: 'Русский' },
];

const readSavedLocale = () => {
    if (typeof window === 'undefined') return fallbackLocale;

    return languages.some((language) => language.code === window.localStorage.getItem(storageKey))
        ? window.localStorage.getItem(storageKey)
        : fallbackLocale;
};

const locale = ref(readSavedLocale());

if (typeof document !== 'undefined') {
    document.documentElement.lang = locale.value;
}

