const resolvePath = (object, path) => path.split('.').reduce((value, segment) => value?.[segment], object);
const localizeFrom = (dictionary, value) => dictionary[value]?.[locale.value] ?? value;

export const useI18n = () => {
    const currentLanguage = computed(() => languages.find((language) => language.code === locale.value) ?? languages[0]);
    const t = (path) => resolvePath(translations[locale.value], path) ?? resolvePath(translations[fallbackLocale], path) ?? path;
    const setLocale = (code) => {
        if (!languages.some((language) => language.code === code)) return;
        locale.value = code;
        window.localStorage.setItem(storageKey, code);
        document.documentElement.lang = code;
    };
    const translate = (dictionaryName, value) => {
        if (locale.value === fallbackLocale) return value;
        return localizeFrom(lists[dictionaryName] ?? {}, value);
    };
    const translateOption = (value) => translate('options', value);
    const mediaLabel = (capacity) => {
        if (capacity === 1) return lists.media.qr[locale.value];
        if (capacity === 2) return lists.media.photoVideo[locale.value];
        return lists.media.photoVideoMusic[locale.value];
    };
    const routeTitle = (routeName, fallback) => lists.routeTitles[routeName]?.[locale.value] ?? fallback;
    const localizedProduct = (product) => {
        const baseSlug = product.slug.replace(/-photo-\d+$/, '');
        const localized = (catalogProducts[product.slug] ?? catalogProducts[baseSlug])?.[locale.value] ?? {};
        const category = translateOption(product.category);
        const occasion = translateOption(product.occasion);
        const material = translateOption(product.material);
        const priceLabel = translate('prices', product.priceLabel);

        return { ...product, ...localized, category, occasion, material, priceLabel };
    };

    return { locale, languages, currentLanguage, setLocale, t, translate, translateOption, mediaLabel, routeTitle, localizedProduct };
};
