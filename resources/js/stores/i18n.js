const getInitialLanguage = () => {
    if (typeof window === 'undefined') return 'lv';

    const savedLanguage = window.localStorage.getItem(STORAGE_KEY);
    if (availableLanguages.includes(savedLanguage)) return savedLanguage;

    const browserLanguage = window.navigator.language?.slice(0, 2).toLowerCase();
    return availableLanguages.includes(browserLanguage) ? browserLanguage : 'lv';
};

const locale = ref(getInitialLanguage());
const languageOptions = [
    { code: 'lv', label: 'LV' },
    { code: 'ru', label: 'RU' },
    { code: 'en', label: 'EN' },
];

const t = computed(() => messages[locale.value] ?? messages.lv);

const setLanguage = (language) => {
    if (!availableLanguages.includes(language)) return;
    locale.value = language;
};

if (typeof window !== 'undefined') {
    watch(locale, (language) => {
        window.localStorage.setItem(STORAGE_KEY, language);
        document.documentElement.lang = language;
    }, { immediate: true });
}

export const useLanguage = () => ({
    locale,
    languageOptions,
    setLanguage,
    t,
});
